"""Initialize once, retain identities, and render the supported 1.20.0 config."""
import configparser
import os
from pathlib import Path
import subprocess

os.umask(0o077)
base = Path('/data/node')
role = os.environ['TAHOE_ROLE']
host = os.environ['TAHOE_HOST']
if not (base / 'tahoe.cfg').exists():
    command = 'create-introducer' if role == 'introducer' else 'create-node'
    subprocess.run(['tahoe', command, '--listen=tcp', '--hostname=' + host, str(base)], check=True)

config = configparser.ConfigParser(interpolation=None)
config.read(base / 'tahoe.cfg')
config['node']['nickname'] = host
config['node']['tub.port'] = 'tcp:3457'
config['node']['tub.location'] = 'tcp:' + host + ':3457'
config['node']['web.port'] = 'tcp:3456:interface=127.0.0.1' if role == 'client' else ''
if role != 'introducer':
    config['storage']['enabled'] = 'true' if role == 'storage' else 'false'
    config['client']['shares.needed'] = '2'
    config['client']['shares.happy'] = '3'
    config['client']['shares.total'] = '3'
    furl = Path('/introducer/introducer.furl').read_text().strip()
    # The FURL is generated by our introducer; JSON strings are valid YAML scalars.
    import json
    (base / 'private' / 'introducers.yaml').write_text(
        'introducers:\n  default:\n    furl: ' + json.dumps(furl) + '\n')
with (base / 'tahoe.cfg').open('w') as out:
    config.write(out)
os.execvp('tahoe', ['tahoe', 'run', '--allow-stdin-close', str(base)])
